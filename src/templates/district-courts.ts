import type { Locale } from '../i18n';
import { cyrillicToLatin } from '../i18n/transliterate';

/**
 * District / interdistrict court within a region. After the user picks
 * one, its `name` is stored in `state.values.district_court_name` and
 * rendered into the document header.
 *
 * Data is the authoritative MySud court registry (mysud.uz official
 * mobile app). Each court has a short legal name + physical address;
 * both are shown in the picker button (name bolder line, address on
 * the second line) so users can pick the correct local court without
 * a separate lookup. Only `name` is written into the document.
 */
export interface DistrictCourtDef {
  code: string;
  regionCode: string;
  courtTypeCode: string;
  /** Short legal name used both for the button label AND written into
   *  the document as `district_court_name`. Templates may prepend
   *  type-prefixes like "Жиноят ишлари бўйича …" or "Фуқаролик ишлари
   *  бўйича …", so names here are kept SHORT (e.g. "Косонсой туман
   *  суди", not "Жиноят ишлари бўйича Косонсой туман суди"). */
  name: Record<Locale, string>;
  /** Physical address. Shown as the second line of the picker button
   *  (greyed-out style is impossible in Telegram inline buttons, but
   *  the second line still helps users disambiguate similarly-named
   *  courts). NOT written into the document. */
  address?: Record<Locale, string>;
}

function L(cy: string, la: string, ru: string): Record<Locale, string> {
  return { uz_cyrillic: cy, uz_latin: la, ru };
}

function D(
  code: string,
  regionCode: string,
  cy: string,
  la: string,
  ru: string,
  addr?: string,
): DistrictCourtDef {
  return {
    code,
    regionCode,
    courtTypeCode: 'fuqarolik',
    name: L(cy, la, ru),
    ...(addr ? { address: { uz_cyrillic: addr, uz_latin: addr, ru: addr } } : {}),
  };
}

/**
 * Compact constructor for non-fuqarolik courts where we have authoritative
 * MySud data. Caller provides:
 *   - cy: Cyrillic Uzbek SHORT name (without "Жиноят/Фуқаролик ишлари
 *     бўйича" prefix — templates add that themselves)
 *   - addr: physical address as shown in MySud (Latin form acceptable for
 *     all locales since addresses are location hints, not legal text)
 *
 * The Latin name is derived via cyrillicToLatin(); the Russian name keeps
 * the Cyrillic form (Russian-speaking Uzbeks read Cyrillic Uzbek place
 * names without issue).
 */
function makeRealCourt(
  type: 'jinoyat' | 'mamuriy' | 'iqtisodiy' | 'fuqarolik',
  code: string,
  regionCode: string,
  cy: string,
  addr: string,
): DistrictCourtDef {
  return {
    code,
    regionCode,
    courtTypeCode: type,
    name: { uz_cyrillic: cy, uz_latin: cyrillicToLatin(cy), ru: cy },
    address: { uz_cyrillic: addr, uz_latin: addr, ru: addr },
  };
}

const M = (code: string, region: string, cy: string, addr: string) =>
  makeRealCourt('mamuriy', code, region, cy, addr);
const I = (code: string, region: string, cy: string, addr: string) =>
  makeRealCourt('iqtisodiy', code, region, cy, addr);
const J = (code: string, region: string, cy: string, addr: string) =>
  makeRealCourt('jinoyat', code, region, cy, addr);
const Fr = (code: string, region: string, cy: string, addr: string) =>
  makeRealCourt('fuqarolik', code, region, cy, addr);

/**
 * Mirror a fuqarolik (civil) court entry to one of the other court
 * types. Cuts down on hand-written duplication — the civil-court list
 * is the source of truth for region/district coverage, and the other
 * three court types are derived from it by swapping the type word in
 * the displayed name.
 *
 * Why per-type substitutions are different:
 *   - jinoyat (criminal): document templates already prepend
 *     "Жиноят ишлари бўйича ..." themselves, so the name must NOT
 *     repeat the word — we strip " фуқаролик" entirely.
 *   - mamuriy (administrative) / iqtisodiy (economic): templates use
 *     the name as-is with just a postposition ("…раисига" / "…га"),
 *     so we swap "фуқаролик" with the appropriate type word.
 *
 * The code prefix changes ("fuq-" → "jin-" / "mam-" / "iqt-") so each
 * court type gets a unique key suitable for callback data.
 */
function mirrorFuqarolikFor(
  base: DistrictCourtDef,
  type: 'jinoyat' | 'mamuriy' | 'iqtisodiy',
): DistrictCourtDef {
  const codePrefix =
    type === 'jinoyat' ? 'jin' : type === 'mamuriy' ? 'mam' : 'iqt';

  const subs: Record<'cy' | 'la' | 'ru', [RegExp, string]> =
    type === 'jinoyat'
      ? {
          cy: [/ фуқаролик/g, ''],
          la: [/ fuqarolik/g, ''],
          ru: [/ гражданский/g, ''],
        }
      : type === 'mamuriy'
        ? {
            cy: [/фуқаролик/g, 'маъмурий'],
            la: [/fuqarolik/g, 'ma’muriy'],
            ru: [/гражданский/g, 'административный'],
          }
        : {
            cy: [/фуқаролик/g, 'иқтисодий'],
            la: [/fuqarolik/g, 'iqtisodiy'],
            ru: [/гражданский/g, 'экономический'],
          };

  return {
    code: base.code.replace(/^fuq-/, `${codePrefix}-`),
    regionCode: base.regionCode,
    courtTypeCode: type,
    name: {
      uz_cyrillic: base.name.uz_cyrillic.replace(subs.cy[0], subs.cy[1]),
      uz_latin: base.name.uz_latin.replace(subs.la[0], subs.la[1]),
      ru: base.name.ru.replace(subs.ru[0], subs.ru[1]),
    },
  };
}

