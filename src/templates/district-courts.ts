/**
 * Set of (courtType, region) pairs that have authoritative MySud data
 * below. For those pairs we use the explicit entries; for pairs NOT
 * in this set we fall back to mirrorFuqarolikFor() so every region/type
 * combination still shows a populated picker. As real MySud data lands
 * for jinoyat / iqtisodiy / etc., move them out of the mirror fallback
 * by adding to REAL_NON_FUQAROLIK_COURTS — the dedupe logic does the
 * rest automatically.
 */
const REAL_NON_FUQAROLIK_COURTS: DistrictCourtDef[] = [
  ...MAMURIY_COURTS,
  ...IQTISODIY_COURTS,
  ...JINOYAT_COURTS,
];

/**
 * Final exported list shown to users. Order:
 *   1. fuqarolik (authoritative)
 *   2. real MySud entries for jin / mam / iqt
 *   3. mirror-fallback for any (type, region) pairs without real data
 */
const REAL_KEYS = new Set(
  REAL_NON_FUQAROLIK_COURTS.map((c) => `${c.courtTypeCode}:${c.regionCode}`),
);
const NON_FUQAROLIK_TYPES = ['jinoyat', 'mamuriy', 'iqtisodiy'] as const;
const MIRRORED_COURTS: DistrictCourtDef[] = FUQAROLIK_COURTS.flatMap((c) =>
  NON_FUQAROLIK_TYPES.filter((t) => !REAL_KEYS.has(`${t}:${c.regionCode}`)).map(
    (t) => mirrorFuqarolikFor(c, t),
  ),
);

export const DISTRICT_COURTS: DistrictCourtDef[] = [
  ...FUQAROLIK_COURTS,
  ...REAL_NON_FUQAROLIK_COURTS,
  ...MIRRORED_COURTS,
];

export function getDistrictCourtByCode(code: string): DistrictCourtDef | undefined {
  return DISTRICT_COURTS.find((d) => d.code === code);
}

/** All district courts for a (courtType, region) pair, in declared order. */
export function getDistrictCourtsFor(
  courtTypeCode: string,
  regionCode: string,
): DistrictCourtDef[] {
  return DISTRICT_COURTS.filter(
    (d) => d.courtTypeCode === courtTypeCode && d.regionCode === regionCode,
  );
}
